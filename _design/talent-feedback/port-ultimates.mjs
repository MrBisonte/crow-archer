// Ports the ten composited ultimate icons into the game's own renderer.
//
//   node port-ultimates.mjs        # ultimates48.js + compose.mjs -> src/render/ultimate-icons.ts
//
// The rest of this directory stops at the design pipeline: `ultimates48.js` is
// generated, gitignored and lives outside src/, so nothing the game builds can
// import it. This is the one step that crosses that line, and it is a script
// rather than a paste for the reason every other file here is generated -- a
// 480-row table copied by hand drifts the first time somebody edits a pixel,
// and nothing would say so.
//
// WHAT IT CARRIES ACROSS IS THE COMPOSITE, not the object. `ultimates48.js`
// holds only what was drawn; the gold bezel, the violet ground, the cast
// shadow and the seam come out of `composite()` here. The art the owner
// approved is the whole picture, so the whole picture is what ships.
//
// WHY ROWS AND A LEGEND. `composite` returns a Map of "x,y" -> hex, and
// writing that out per icon is a 48x48 array of hex strings -- about a
// megabyte of tracked source for ten pictures. The union of every colour the
// ten use is 52, which fits one shared legend of single characters, so the
// same picture costs 48 strings of 48 characters per icon and diffs like the
// drawings in `ultimates/` do.
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { composite } from './compose.mjs';
import { ULTIMATES } from './ultimates48.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, '../../src/render/ultimate-icons.ts');

/** The grid every ultimate is drawn on. Read off the icons rather than
 *  assumed, so a set that ever changes size fails here instead of silently
 *  emitting rows the painter will crop. */
const N = 48;

/**
 * The legend alphabet. Letters and digits only: no quote, no backslash, and
 * nothing a shell heredoc or a TypeScript string literal has an opinion about.
 * `.` is reserved for a cell the bezel's rounded corner leaves empty.
 */
const CHARS = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz';

const drawn = ULTIMATES.map((icon) => {
  if ((icon.size ?? 32) !== N) throw new Error(`${icon.id} is ${icon.size} px; the port expects ${N}`);
  return { id: icon.id, px: composite(icon) };
});
if (!drawn.length) throw new Error('ultimates48.js has no icons -- run draw-ultimates.py first');

// Sorted, so the same ten icons always get the same ten characters and a
// re-run with nothing changed produces a byte-identical file.
const colours = [...new Set(drawn.flatMap(({ px }) => [...px.values()]))].sort();
if (colours.length > CHARS.length) {
  throw new Error(`${colours.length} colours and only ${CHARS.length} characters to name them with`);
}
const charOf = new Map(colours.map((c, i) => [c, CHARS[i]]));

const rowsOf = ({ px }) => Array.from({ length: N }, (_, y) =>
  Array.from({ length: N }, (_, x) => charOf.get(px.get(`${x},${y}`)) ?? '.').join(''));

const legend = colours
  .map((c) => `  '${charOf.get(c)}': '${c}',`)
  .join('\n');

const icons = drawn
  .map((icon) => `  ${icon.id}: [\n`
    + rowsOf(icon).map((r) => `    '${r}',\n`).join('')
    + '  ],\n')
  .join('');

const HEADER = `/**
 * The ten ultimate icons, composited, as rows against a shared legend.
 *
 * GENERATED by \`_design/talent-feedback/port-ultimates.mjs\` from the drawings
 * in \`_design/talent-feedback/ultimates/\` and the frame \`compose.mjs\` puts
 * round them. Edit there and re-run it; a pixel changed here is lost.
 *
 * WHAT IS IN THE PICTURE. Not just the drawn object: the gold bezel that says
 * "ultimate" before the object is read, the violet ground shared by all ten,
 * the shadow the object casts on it and the warm seam round its lit edges are
 * all generated by \`composite()\` and baked in here. They are the same picture
 * the design canvas shows, which is the only reason it is worth carrying them
 * across rather than re-deriving them at runtime.
 *
 * A \`.\` is a cell no colour reaches -- outside the bezel's rounded corner --
 * and paints nothing. Every other character is a key into ULTIMATE_ICON_LEGEND.
 *
 * The ids are the abilities' own, from \`ULTIMATE\` in \`src/legacy/game.js\`.
 * \`ultimate-tables.test.ts\` holds the two sets to each other, so an ability
 * renamed cannot leave an icon for something that no longer exists.
 *
 * Nothing here says what an ultimate is called or which hero owns it. That
 * lives in the ability table and has one home; this file is the drawing.
 */

/** The grid every icon is drawn on: ${N} rows of ${N} characters. */
export const ULTIMATE_ICON_SIZE = ${N};

/** Every colour the ten composites use, named by the character rows spell it
 *  with. Shared rather than one legend per icon: the ten differ only in the
 *  object, so ${colours.length} entries cover the set. */
export const ULTIMATE_ICON_LEGEND: Readonly<Record<string, string>> = {
${legend}
};

/** One icon per ultimate, keyed by the ability id. */
export const ULTIMATE_ICON_ROWS: Readonly<Record<string, readonly string[]>> = {
`;

writeFileSync(OUT, `${HEADER}${icons}};\n`, { encoding: 'utf8' });
console.log(`wrote ${OUT} -- ${drawn.length} icons, ${colours.length} colours`);
